import json
import logging
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

# NO streamlit import — this is a standalone file exporter with no UI

logger = logging.getLogger(__name__)
DEFAULT_EXPORT_DIR = Path("notebooklm_exports")


class NotebookLMExporter:
    def __init__(self, export_dir: Optional[Path] = None) -> None:
        self.export_dir = Path(export_dir) if export_dir else DEFAULT_EXPORT_DIR
        self.export_dir.mkdir(parents=True, exist_ok=True)

    def export_weekly_digest(
        self,
        analyses: List[Dict[str, Any]],
        week: Optional[str] = None,
    ) -> Path:
        week = week or datetime.now().strftime("%Y-W%W")
        filename = f"QuantEdge_Weekly_Digest_{week}.md"
        path = self.export_dir / filename
        now = datetime.now()

        content = f"# QuantEdge Weekly Trading Digest — {week}\n\n"
        content += f"**Generated:** {now.strftime('%Y-%m-%d %H:%M')}  \n"
        content += f"**Platform:** QuantEdge Institutional Trading Intelligence  \n"
        content += f"**Analyses:** {len(analyses)}\n\n---\n\n"

        for i, analysis in enumerate(analyses, 1):
            atype = analysis.get("type", "Analysis")
            symbol = analysis.get("symbol", "MARKET")
            data = analysis.get("data", {})
            content += f"## {i}. {atype} — {symbol.upper()}\n\n"
            content += f"**Date:** {analysis.get('date', now.strftime('%Y-%m-%d'))}  \n"
            content += f"**Symbol:** {symbol.upper()}\n\n"

            if atype == "Elliott Wave":
                valid = data.get("valid_structure", False)
                ratio = data.get("retrace_ratio", "N/A")
                target = data.get("target_1618", "N/A")
                w4 = data.get("w4_valid", False)
                content += f"- Valid Structure: {'Yes' if valid else 'No'}\n"
                content += f"- Wave 2 Retrace: {ratio}\n"
                content += f"- Rule 3 (No Overlap): {'PASS' if w4 else 'VIOLATION'}\n"
                if target != "N/A":
                    try:
                        content += f"- Wave 3 Target: ${float(target):,.2f}\n"
                    except (TypeError, ValueError):
                        content += f"- Wave 3 Target: {target}\n"
            elif atype == "AI Analysis":
                content += f"**Query:** {data.get('query', '')}\n\n"
                content += f"{data.get('insights', data.get('response', ''))}\n"
            elif atype == "Swedish":
                content += f"- Price: {data.get('price', 'N/A')} SEK\n"
                content += f"- Change: {data.get('change_pct', 0):+.2f}%\n"
                content += f"- ISK: {'Yes' if data.get('isk_eligible') else 'No'}\n"
            elif atype == "Signal":
                content += f"- Direction: {data.get('direction', 'WATCH')}\n"
                content += f"- Entry: {data.get('entry', 'N/A')}\n"
                content += f"- Stop: {data.get('stop', 'N/A')}\n"
                content += f"- Target: {data.get('target', 'N/A')}\n"
            else:
                content += f"```json\n{json.dumps(data, indent=2, default=str)}\n```\n"
            content += "\n---\n\n"

        content += (
            "## Upload to NotebookLM\n\n"
            "1. Go to https://notebooklm.google.com\n"
            "2. Open your notebook\n"
            "3. Click **Add Source** → **Upload file**\n"
            "4. Upload this `.md` file\n"
            "5. Ask questions or click **Audio Overview**\n\n"
            "*Generated by QuantEdge Institutional Trading Intelligence*\n"
        )

        path.write_text(content, encoding="utf-8")
        logger.info(f"Saved: {path}")
        return path

    def export_market_briefing(
        self,
        market_data: Dict[str, Any],
        ai_summary: Optional[str] = None,
    ) -> Path:
        date_str = datetime.now().strftime("%Y-%m-%d")
        path = self.export_dir / f"Market_Briefing_{date_str}.md"
        content = f"# QuantEdge Market Briefing — {date_str}\n\n"
        content += "## Market Pulse\n\n"
        if isinstance(market_data, dict):
            content += "| Symbol | Price | Change |\n|---|---|---|\n"
            for tkr, d in market_data.items():
                if isinstance(d, dict):
                    chg = d.get("change", 0)
                    arrow = "▲" if d.get("up", True) else "▼"
                    content += f"| {d.get('name', tkr)} | {d.get('current', 0):.2f} | {arrow} {chg:+.2f}% |\n"
            content += "\n"
        if ai_summary:
            content += f"## AI Summary\n\n{ai_summary}\n\n"
        path.write_text(content, encoding="utf-8")
        return path


